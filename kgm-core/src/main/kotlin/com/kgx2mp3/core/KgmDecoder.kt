    /** Returns true for the KGM/KGMA magic, including newer unsupported variants. */
    fun isEncryptedHeader(bytes: ByteArray): Boolean =
        bytes.size >= KGM_HEADER.size && KGM_HEADER.indices.all { bytes[it] == KGM_HEADER[it] }

    fun decrypt(
        input: InputStream,
        output: OutputStream,
        bufferSize: Int = 65536,
        checkCancelled: () -> Unit = {}
    ): AudioFormat {
        require(bufferSize in 1..MAX_BUFFER) { "Buffer size must be between 1 and $MAX_BUFFER" }
        checkCancelled()
        val prefix = ByteArray(HEADER_MIN)
        readExactly(input, prefix, checkCancelled, "KGM 檔頭不完整")
        if (!isEncryptedHeader(prefix)) throw KgmDecodingException("不是支援的 KGM／KGMA 檔案")
        val headerLength = littleEndianUInt(prefix, 0x10)
        if (headerLength !in HEADER_MIN.toLong()..MAX_HEADER) {
            throw KgmDecodingException("KGM 檔頭長度不正確：$headerLength")
        }
        val version = littleEndianUInt(prefix, 0x14)
        val type = littleEndianUInt(prefix, 0x18)
        if (version != 3L || type != 1L) {
            throw KgmDecodingException("尚不支援的 KGM 加密版本（版本 $version，類型 $type）")
        }
        val key = ByteArray(17)
        prefix.copyInto(key, 0, 0x1C, 0x2C)
        discardExactly(input, headerLength - HEADER_MIN, checkCancelled)

        // Collect a fixed, small decrypted prefix before writing any output.
        // Small reads/buffers do not change format detection or cipher offsets.
        val probe = ByteArray(PROBE_SIZE)
        var probeSize = 0
        while (probeSize < probe.size) {
            checkCancelled()
            val count = readProgress(input, probe, probeSize, probe.size - probeSize)
            if (count < 0) break
            probeSize += count
        }
        if (probeSize == 0) throw KgmDecodingException("KGM 檔案沒有音訊內容")
        decryptBlock(probe, probeSize, 0L, key)
        val format = AudioSniffer.detect(probe.copyOf(probeSize))
            ?: throw KgmDecodingException("解密結果不是可識別的音樂，可能是未知加密版本或檔案損壞")
        checkCancelled()
        output.write(probe, 0, probeSize)

        var offset = probeSize.toLong()
        val buffer = ByteArray(bufferSize)
        while (true) {
            checkCancelled()
            val count = readProgress(input, buffer, 0, buffer.size)
            if (count < 0) break
            if (offset > Long.MAX_VALUE - count) throw KgmDecodingException("KGM 音訊長度超出支援範圍")
            decryptBlock(buffer, count, offset, key)
            checkCancelled()
            output.write(buffer, 0, count)
            offset += count
        }
        checkCancelled()
        return format
    }

    /** Stateless transform; Long offsets prevent corruption after 2 GiB. */
    internal fun decryptBlock(buffer: ByteArray, count: Int, startOffset: Long, key: ByteArray) {
        require(count in 0..buffer.size && key.size == 17 && startOffset >= 0)
        require(startOffset <= Long.MAX_VALUE - count)
        for (i in 0 until count) {
            val position = startOffset + i
            val keyByte = key[(position % 17L).toInt()].toInt() and 0xFF
            var value = keyByte xor (buffer[i].toInt() and 0xFF)
            value = value xor ((value and 0x0F) shl 4)
            var mask = maskForOffset(position)
            mask = mask xor ((mask and 0x0F) shl 4)
            buffer[i] = (value xor mask).toByte()
        }
    }

    private fun maskForOffset(position: Long): Int {
        var offset = position ushr 4
        var value = 0
        while (offset >= 0x11) {
            value = value xor (TABLE1[(offset % 272L).toInt()].toInt() and 0xFF)
            offset = offset ushr 4
            value = value xor (TABLE2[(offset % 272L).toInt()].toInt() and 0xFF)
            offset = offset ushr 4
        }
        return (MASK_V2_PRE_DEF[(position % 272L).toInt()].toInt() and 0xFF) xor value
    }

    private fun littleEndianUInt(bytes: ByteArray, offset: Int): Long =
        (0..3).fold(0L) { value, index ->
            value or ((bytes[offset + index].toLong() and 0xFF) shl (index * 8))
        }

    private fun readExactly(
        input: InputStream,
        bytes: ByteArray,
        checkCancelled: () -> Unit,
        failureMessage: String
    ) {
        var consumed = 0
        while (consumed < bytes.size) {
            checkCancelled()
            val count = readProgress(input, bytes, consumed, bytes.size - consumed)
            if (count < 0) throw KgmDecodingException(failureMessage)
            consumed += count
        }
    }

    private fun discardExactly(input: InputStream, count: Long, checkCancelled: () -> Unit) {
        var remaining = count
        val discard = ByteArray(minOf(8192L, maxOf(1L, remaining)).toInt())
        while (remaining > 0) {
            checkCancelled()
            val read = readProgress(input, discard, 0, minOf(remaining, discard.size.toLong()).toInt())
            if (read < 0) throw KgmDecodingException("KGM 檔頭不完整")
            remaining -= read
        }
    }

    // A legal blocking InputStream should not return zero for a nonempty read,
    // but unusual document providers sometimes do. Fall back to one byte.
    private fun readProgress(input: InputStream, bytes: ByteArray, offset: Int, length: Int): Int {
        val count = input.read(bytes, offset, length)
        if (count != 0) return count
        val single = input.read()
        if (single < 0) return -1
        bytes[offset] = single.toByte()
        return 1
    }
